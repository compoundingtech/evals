#!/usr/bin/env bash
# Generate or verify the single current catalog/evidence surface.
set -euo pipefail

repo_root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$repo_root"

mode="${1:---check}"
if [ "$mode" != "--check" ] && [ "$mode" != "--write" ]; then
  echo "usage: bin/generate-catalog.sh [--check|--write]" >&2
  exit 2
fi

inventory="$(mktemp)"
generated="$(mktemp)"
cleanup() {
  [ -z "$inventory" ] || rm -f -- "$inventory"
  [ -z "$generated" ] || rm -f -- "$generated"
}
trap cleanup EXIT

bin/corpus-inventory.sh --no-header > "$inventory"

declare -A evidence_date=()
declare -A evidence_st2=()
declare -A evidence_duration=()
declare -A evidence_result=()
declare -A evidence_usage=()
declare -A evidence_commit=()

header=""
while IFS=$'\t' read -r cell date st2_commit duration result usage commit; do
  if [ -z "$header" ]; then
    header="$cell	$date	$st2_commit	$duration	$result	$usage	$commit"
    [ "$header" = $'cell\tdate_utc\tst2_commit\tduration\tresult\tusage_notice\tevidence_commit' ] || {
      echo "FAIL: evidence/model-runs.tsv has an unexpected header" >&2
      exit 1
    }
    continue
  fi
  [ -n "$cell" ] || continue
  [ -z "${evidence_result[$cell]:-}" ] || {
    echo "FAIL: duplicate evidence row for $cell" >&2
    exit 1
  }
  grep -q "^${cell}"$'\t' "$inventory" || {
    echo "FAIL: evidence names excluded or missing cell $cell" >&2
    exit 1
  }
  [ "$result" = "PASS" ] || {
    echo "FAIL: only completed PASS evidence belongs in model-runs.tsv ($cell is $result)" >&2
    exit 1
  }
  git cat-file -e "$commit^{commit}" 2>/dev/null || {
    echo "FAIL: evidence commit for $cell is not present: $commit" >&2
    exit 1
  }
  evidence_date[$cell]="$date"
  evidence_st2[$cell]="$st2_commit"
  evidence_duration[$cell]="$duration"
  evidence_result[$cell]="$result"
  evidence_usage[$cell]="$usage"
  evidence_commit[$cell]="$commit"
done < evidence/model-runs.tsv

excluded=0
exclusion_rows=""
header=""
while IFS=$'\t' read -r cell reason; do
  if [ -z "$header" ]; then
    header="$cell	$reason"
    [ "$header" = $'cell\treason' ] || {
      echo "FAIL: evidence/exclusions.tsv has an unexpected header" >&2
      exit 1
    }
    continue
  fi
  [ -n "$cell" ] || continue
  [ ! -e "cells/$cell" ] || {
    echo "FAIL: excluded cell still exists: cells/$cell" >&2
    exit 1
  }
  exclusion_rows+="- \`$cell\` — $reason"$'\n'
  ((excluded += 1))
done < evidence/exclusions.tsv

harness_exclusions=0
harness_exclusion_rows=""
header=""
while IFS=$'\t' read -r cell surface reason; do
  if [ -z "$header" ]; then
    header="$cell	$surface	$reason"
    [ "$header" = $'cell\tsurface\treason' ] || {
      echo "FAIL: evidence/harness-exclusions.tsv has an unexpected header" >&2
      exit 1
    }
    continue
  fi
  [ -n "$cell" ] || continue
  grep -q "^${cell}"$'\t' "$inventory" || {
    echo "FAIL: harness exclusion names missing cell $cell" >&2
    exit 1
  }
  harness_exclusion_rows+="- \`$cell\` / \`$surface\` — $reason"$'\n'
  ((harness_exclusions += 1))
done < evidence/harness-exclusions.tsv

total=0
model_free=0
model_backed=0
while IFS=$'\t' read -r cell harness models effort seats cost timeout judges; do
  ((total += 1))
  if [ "$harness" = "model-free" ]; then
    ((model_free += 1))
  else
    ((model_backed += 1))
  fi
done < "$inventory"

{
  cat <<EOF
<!-- Generated by bin/generate-catalog.sh from cell KDL and evidence/*.tsv. Do not edit. -->
# Current eval catalog and evidence

This is the sole current corpus surface: **$total included cells** ($model_free model-free,
$model_backed model-backed) and **$excluded retired exclusions**. Inventory fields are derived from the active
KDL and executable judge scripts. Historical model evidence is structured and commit-checked; it proves the
scenario lineage at the named commit, not an unrecorded rerun of current source.

Every model launch is explicitly pinned by \`bin/check-model-policy.sh\`: Claude uses
\`claude-sonnet-5\` at medium effort and Codex uses \`gpt-5.6-sol\` at medium reasoning effort.
Every bus-connected model seat is mechanically checked for the event-first DING lifecycle and its
harness-native loader plus canonical hook file.

## Included overnight inventory

| Cell | Harness | Model(s) / effort | Model seats | Cost | Timeout | Held-out judges | Last recorded model evidence |
|---|---|---|---:|---|---|---:|---|
EOF

  while IFS=$'\t' read -r cell harness models effort seats cost timeout judges; do
    if [ "$models" = "-" ]; then
      model_display="—"
    else
      model_display="\`$models\` / $effort"
    fi
    if [ -n "${evidence_result[$cell]:-}" ]; then
      commit="${evidence_commit[$cell]}"
      short="${commit:0:7}"
      usage="${evidence_usage[$cell]}"
      evidence="**${evidence_result[$cell]}** ${evidence_date[$cell]}, st2 \`${evidence_st2[$cell]}\`, ${evidence_duration[$cell]}, [\`$short\`](https://github.com/compoundingtech/evals/commit/$commit)"
      if [ "$usage" != "none" ]; then
        evidence+="; usage notice: $usage"
      fi
    else
      evidence="—"
    fi
    printf '| `%s` | %s | %s | %s | %s | `%s` | %s | %s |\n' \
      "$cell" "$harness" "$model_display" "$seats" "$cost" "$timeout" "$judges" "$evidence"
  done < "$inventory"

  cat <<EOF

## Excluded retired cells

$exclusion_rows
\`hook-integrity\` is not excluded: it is now a model-free, current-native
\`st2 up --materialize-only\` hook installation and idempotency test.

## Harness hook exclusions

$harness_exclusion_rows
These **$harness_exclusions** rows are generated from structured exclusions. A cell-level row is required for
every derived model-free cell. The one-shot docs cold reader is a model-backed grader, but not a bus-connected
agent: it has no st2 identity, DING sidecar, or lifecycle hooks.

## Free gate and overnight commands

Run the complete model-free preflight:

\`\`\`sh
bin/check-corpus.sh
\`\`\`

Preview the exact lexical run order, harness, model, effort, seat count, cost band, and timeout:

\`\`\`sh
bin/overnight.sh --dry-run
bin/overnight.sh --dry-run --cell ghost-bug --cell ghost-bug-codex
\`\`\`

The conservative future paid run requires an exact repeated \`--cell\` queue and stops before the next cell on
either a hard usage error or the informational Codex reset-available banner:

\`\`\`sh
bin/overnight.sh --run --cell ghost-bug --cell ghost-bug-codex --state-dir .eval-runs/overnight
\`\`\`

Because that common informational banner would prevent a full unattended sweep, the exact future full-run
command makes both its complete-inventory selection and separately reviewed higher-spend choice visible:

\`\`\`sh
bin/overnight.sh --run --all --allow-informational-reset-banner --state-dir .eval-runs/overnight
\`\`\`

With no selector, dry-run remains inventory-only; paid \`--run\` rejects omitted, duplicate, unknown, retired,
and model-free selections. Neither \`--all\` nor the informational-banner opt-in is approved merely because it
is documented or shown by \`--dry-run\`.

The runner executes one cell at a time, applies each cell's declared timeout plus a watchdog grace period,
keeps durable logs and atomic PASS receipts, and skips matching completed receipts on resume. Hard quota/rate
errors always write \`STOPPED\`. A Codex \`N usage limit resets available\` banner is modeled separately: its
active cell tears down and records a result, then the default blocks the next cell; only
\`--allow-informational-reset-banner\` permits another paid cell after that banner. It never overlaps Claude
and Codex cells.
EOF
} > "$generated"

if [ "$mode" = "--write" ]; then
  mv -- "$generated" CATALOG.md
  generated=""
  echo "wrote CATALOG.md"
elif ! cmp -s "$generated" CATALOG.md; then
  echo "FAIL: CATALOG.md is stale; run bin/generate-catalog.sh --write" >&2
  diff -u CATALOG.md "$generated" >&2 || true
  exit 1
else
  echo "PASS: CATALOG.md matches the active corpus and structured evidence"
fi
